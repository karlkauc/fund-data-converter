"""openfunds template fields (OFEM, OFEP, OFEE, OFEF) ↔ the FundsXML FinDatEx template blocks.

The mapping is generated by ``tools/build_openfunds_templates.py`` (``openfunds_templates.json``):
every openfunds field names its FinDatEx template field, and FundsXML documents the same numbers
on the elements of ``EMT_V4_3``, ``EET1.1.3``, ``EFTs`` and ``PRIIPS_V20``. One template record is
written per share class record that has values for it.

Values differ only in form: openfunds ``yes``/``no`` ↔ ``Y``/``N`` or ``YES``/``NO``, openfunds
decimal fractions ↔ ``PercentageType`` percent, lists separated by ``;`` ↔ repeated elements, and a
few version codes (``v4.3`` ↔ ``V4S3``). A value counts as lossless only if it reads back unchanged.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from decimal import Decimal
from functools import lru_cache
from pathlib import Path

from app.model.xmltree import format_decimal, parse_decimal
from app.spec.openfunds import load_openfunds

TEMPLATES_JSON = Path(__file__).resolve().parent / "openfunds_templates.json"
_YES = {"yes", "y", "true"}
_NO = {"no", "n", "false"}


@dataclass(frozen=True)
class TemplateField:
    of_id: str
    template: str  # EMT, EET, EFT, EPT
    num: str
    path: str  # relative to the template record
    enums: tuple[str, ...]
    many: bool  # repeated element: openfunds list "A;B"
    percent: bool  # openfunds fraction ↔ FundsXML percent
    codes: dict[str, str]  # openfunds value -> schema value, where they differ in spelling

    def to_xml(self, value: str) -> list[str]:
        """Schema values for an openfunds value (several for a list); empty if it has none."""
        items = [v.strip() for v in value.split(";")] if self.many else [value.strip()]
        out = []
        for item in items:
            if not item:
                continue
            xml = self._one(item)
            if xml is None:
                return []
            out.append(xml)
        return out

    def from_xml(self, values: list[str]) -> str:
        return ";".join(v for v in (self._back(x) for x in values) if v is not None)

    def _one(self, v: str) -> str | None:
        low = v.lower()
        for k, x in self.codes.items():
            if k.lower() == low:
                return x
        if self.enums:
            exact = next((e for e in self.enums if e.lower() == low), None)
            if exact is not None:
                return exact
            if low in _YES:
                return next((e for e in self.enums if e.upper() in ("Y", "YES")), None)
            if low in _NO:
                return next((e for e in self.enums if e.upper() in ("N", "NO")), None)
            return None
        if self.percent:
            try:
                return format_decimal(parse_decimal(v) * 100)
            except ValueError:
                return v
        return v

    def _back(self, x: str) -> str | None:
        x = x.strip()
        for k, v in self.codes.items():
            if v == x:
                return k
        if self.enums:
            if x.upper() in ("Y", "YES"):
                return "yes"
            if x.upper() in ("N", "NO"):
                return "no"
            codes = load_openfunds().by_id[self.of_id].codes
            return next((c for c in codes if c.lower() == x.lower()), x)
        if self.percent:
            try:
                return format_decimal(parse_decimal(x) / Decimal(100))
            except ValueError:
                return x
        return x

    def lossless(self, value: str) -> bool:
        xml = self.to_xml(value)
        if not xml:
            return False
        back = self.from_xml(xml)
        if back == value.strip():
            return True
        try:
            return not self.many and parse_decimal(back) == parse_decimal(value)
        except ValueError:
            return False


@dataclass(frozen=True)
class Template:
    name: str
    record: str  # record element path from the document root
    fields: tuple[TemplateField, ...]

    @property
    def container(self) -> str:
        """Path below ``RegulatoryReportings`` of the element holding the records."""
        return self.record.split("/", 1)[1].rsplit("/", 1)[0]

    @property
    def element(self) -> str:
        return self.record.rsplit("/", 1)[1]


@lru_cache(maxsize=1)
def templates() -> tuple[Template, ...]:
    data = json.loads(TEMPLATES_JSON.read_text(encoding="utf-8"))
    by_template: dict[str, list[TemplateField]] = {}
    for f in data["fields"]:
        by_template.setdefault(f["template"], []).append(
            TemplateField(
                f["id"],
                f["template"],
                f["num"],
                f["path"],
                tuple(f["enums"]),
                f["many"],
                f["percent"],
                f.get("codes", {}),
            )
        )
    return tuple(Template(t, record, tuple(by_template.get(t, ()))) for t, record in data["records"].items())


@lru_cache(maxsize=1)
def template_ids() -> frozenset[str]:
    return frozenset(f.of_id for t in templates() for f in t.fields)
